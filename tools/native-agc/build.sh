# Rebuilds src/SharpEmu.Core/Cpu/Native/NativeAgcCode.g.cs from native_agc.c.
# Needs gcc, binutils (objdump, objcopy, nm) and python3.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
out="$here/../../src/SharpEmu.Core/Cpu/Native/NativeAgcCode.g.cs"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
gcc -O2 -c -fPIC -ffreestanding -fno-builtin -fno-tree-loop-distribute-patterns -mgeneral-regs-only -mno-red-zone \
    -fno-stack-protector -fno-asynchronous-unwind-tables -fno-jump-tables -fcf-protection=none \
    -o "$tmp/native_agc.o" "$here/native_agc.c"
if objdump -dr "$tmp/native_agc.o" | grep -E '\bcall|R_X86_64' >&2; then
    echo "native_agc.c must compile to code with no calls and no relocations" >&2
    exit 1
fi
objcopy -O binary --only-section=.text "$tmp/native_agc.o" "$tmp/text.bin"
nm "$tmp/native_agc.o" > "$tmp/symbols.txt"
objdump -h "$tmp/native_agc.o" > "$tmp/sections.txt"
python3 - "$tmp" "$out" <<'PY'
import sys, re
tmp, out = sys.argv[1], sys.argv[2]
for line in open(f"{tmp}/sections.txt"):
    parts = line.split()
    if len(parts) > 2 and re.match(r"\.(rodata|data|bss)", parts[1]) and int(parts[2], 16) > 0:
        sys.exit(f"native_agc.c must not use data sections ({parts[1]})")
code = open(f"{tmp}/text.bin", "rb").read()
symbols = []
for line in open(f"{tmp}/symbols.txt"):
    value, kind, name = line.split()
    if kind == "T" and name.startswith("agc_"):
        pascal = "".join(p.capitalize() for p in name[4:].split("_"))
        symbols.append((int(value, 16), pascal))
lines = [
    "// Copyright (C) 2026 SharpEmu Emulator Project",
    # Split so the REUSE tool does not read this line as the script's own license.
    "// SPDX-" "License-Identifier: GPL-2.0-or-later",
    "",
    "// <auto-generated>Written by tools/native-agc/build.sh from tools/native-agc/native_agc.c. Do not edit.</auto-generated>",
    "",
    "namespace SharpEmu.Core.Cpu.Native;",
    "",
    "internal static class NativeAgcCode",
    "{",
]
lines += [f"    internal const int {name} = 0x{offset:X};" for offset, name in sorted(symbols)]
lines += ["", "    internal static ReadOnlySpan<byte> Text =>", "    ["]
for i in range(0, len(code), 16):
    lines.append("        " + " ".join(f"0x{b:02X}," for b in code[i:i + 16]))
lines += ["    ];", "}", ""]
open(out, "w").write("\n".join(lines))
print(f"wrote {out} ({len(code)} bytes of code, {len(symbols)} entry points)")
PY
